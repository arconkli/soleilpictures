// Writes src/sheetIcons.js: the Phosphor icons' regular-weight path data, for
// the contact sheet and the names picture (the box has no React to draw them).
//   node media/scripts/gen-sheet-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const NAMES = ['FolderSimple', 'File', 'FilePdf', 'FileText', 'FileImage', 'FileVideo', 'FileAudio', 'FileZip', 'FileCode'];
const root = fileURLToPath(new URL('../../boards/node_modules/@phosphor-icons/react/', import.meta.url));
const version = JSON.parse(readFileSync(`${root}package.json`, 'utf8')).version;

const icons = {};
for (const name of NAMES) {
  const src = readFileSync(`${root}dist/defs/${name}.es.js`, 'utf8');
  const from = src.indexOf('"regular"');
  const to = src.indexOf('"thin"');
  if (from < 0 || to < from) throw new Error(`${name}: no regular weight found`);
  const paths = [...src.slice(from, to).matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${name}: no path data in the regular weight`);
  icons[name] = paths;
}

const body = NAMES.map((n) => `  ${n}: ${JSON.stringify(icons[n])},`).join('\n');
writeFileSync(
  fileURLToPath(new URL('../src/sheetIcons.js', import.meta.url)),
  `// Generated by media/scripts/gen-sheet-icons.mjs from @phosphor-icons/react ${version}
// (regular weight, 256x256 viewBox). Don't edit by hand.
export const SHEET_ICONS = Object.freeze({
${body}
});
`,
);
