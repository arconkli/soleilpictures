#!/usr/bin/env node
// Regenerate src/lib/buildInfo.js with the current commit's date + short SHA,
// and the party host this build's bundle talks to.
// Runs as the `prebuild` npm hook, so both local `npm run build` and Cloudflare
// Workers Builds stamp the artifact before vite/wrangler bundle it. The Worker
// serves the stamp at /api/build-info; the SEO health check compares it against
// an expected minimum to catch "prod isn't serving what we shipped", and an open
// tab compares `party` with its own (lib/buildWatch.js) to know the party moved.
//
// PARTY_HOST is lib/partyHost.js's answer, computed the way Vite will compute
// it for this build: VITE_PARTY_HOST if set (loadEnv: the process environment,
// which is where Workers Builds puts its build variables, over .env files), else
// the default in lib/partyDefaults.js. Every client module reads the stamped
// value through partyHost.js, so a tab and the Worker serving it can only
// disagree when they come from different builds.

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';
import { DEFAULT_PARTY_HOST } from '../src/lib/partyDefaults.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/lib/buildInfo.js');

let date = new Date().toISOString().slice(0, 10);
let sha = 'unknown';
try {
  date = execSync('git log -1 --format=%cs', { cwd: HERE }).toString().trim() || date;
  sha = execSync('git log -1 --format=%h', { cwd: HERE }).toString().trim() || sha;
} catch (_) {
  // Not a git checkout (some CI tarballs) — fall back to today's date.
}

const env = loadEnv('production', resolve(HERE, '..'), 'VITE_');
let party = (env.VITE_PARTY_HOST || DEFAULT_PARTY_HOST).trim();
// Anything that is not a bare host[:port] is stamped empty, which switches the
// watcher off for this build rather than failing the build over it.
if (!/^[a-z0-9.-]+(:\d+)?$/i.test(party)) {
  console.warn(`stamp-build: party host ${JSON.stringify(party)} is not a bare host; PARTY_HOST left empty`);
  party = '';
}

writeFileSync(OUT, `// Build stamp — REGENERATED by scripts/stamp-build.mjs (prebuild hook) with the
// current commit's date + short SHA at build time. This committed fallback only
// exists so a bare checkout compiles; 'dev' means "not a stamped build".
// Served by the Worker at /api/build-info for the SEO health/drift detector:
// "is production actually running the code we shipped?"
export const BUILD_DATE = '${date}';
export const BUILD_SHA = '${sha}';
// The party host this build's bundle uses (lib/buildWatch.js). '' = unstamped.
export const PARTY_HOST = '${party}';
`);
console.log(`✓ buildInfo.js stamped: ${date} @ ${sha}, party ${party}`);
