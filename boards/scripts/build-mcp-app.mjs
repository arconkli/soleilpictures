#!/usr/bin/env node
// build-mcp-app.mjs — pack the inline view (boards/mcp-app/src/) into one HTML
// page, as the string src/lib/mcpAppHtml.generated.js exports. The hosted MCP
// server answers resources/read with it, and the npm package carries a copy
// (mcp/scripts/sync-tools.mjs).
//
// The output is committed, as the docs are: the Worker's build never runs
// this. `--check` says whether building again would change it, which
// mcpApp.test.mjs runs, so an edit to the view that wasn't rebuilt fails the
// tests.
//
// Usage:
//   node scripts/build-mcp-app.mjs            write src/lib/mcpAppHtml.generated.js
//   node scripts/build-mcp-app.mjs --check    exit 1 if that file would change

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build, transform } from 'esbuild';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, '..', 'mcp-app', 'src');
export const OUT = path.join(HERE, '..', 'src', 'lib', 'mcpAppHtml.generated.js');

// One target for every host's browser frame: what the app itself supports.
const TARGET = ['chrome111', 'safari16.4', 'firefox115'];

export async function buildPage() {
  const js = await build({
    entryPoints: [path.join(SRC, 'main.js')],
    bundle: true,
    format: 'iife',
    minify: true,
    target: TARGET,
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  const css = await transform(await readFile(path.join(SRC, 'view.css'), 'utf8'), {
    loader: 'css', minify: true, target: TARGET, charset: 'utf8',
  });
  const page = await readFile(path.join(SRC, 'page.html'), 'utf8');
  const script = js.outputFiles[0].text.trim();
  const style = css.code.trim();
  // Inside the page these would end the script or the style early (esbuild
  // escapes them in strings; this says so if that ever stops being true).
  if (/<\/script|<!--/i.test(script) || /<\/style/i.test(style)) throw new Error('the view holds a sequence that ends its tag');
  if (!page.includes('/*VIEW_JS*/') || !page.includes('/*VIEW_CSS*/')) throw new Error('page.html lost its placeholders');
  return page
    .replace('/*VIEW_CSS*/', () => style)
    .replace('/*VIEW_JS*/', () => script)
    .trim();
}

export const moduleText = (html) => '// GENERATED by scripts/build-mcp-app.mjs from boards/mcp-app/src/ — do not edit.\n'
  + '// The inline view show_board opens in an AI chat (an MCP App), as one page.\n'
  + `export const MCP_APP_HTML = ${JSON.stringify(html)};\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = moduleText(await buildPage());
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = await readFile(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (now !== text) {
      console.error('src/lib/mcpAppHtml.generated.js is stale: run `npm run mcp-app:build` and commit it.');
      process.exit(1);
    }
    console.log('mcp-app: up to date');
  } else {
    await writeFile(OUT, text);
    console.log(`mcp-app: wrote ${path.relative(process.cwd(), OUT)} (${(Buffer.byteLength(text) / 1024).toFixed(1)} KB)`);
  }
}
