// The names the app writes into people's data (a new doc, page, cluster), in
// every language. A name that code compares later is written with
// t({ message: 'Untitled doc', context: 'default name' }); this reads every
// catalog for those entries and writes src/lib/defaultNames.data.js, which
// src/lib/defaultNames.js (plain data, safe for the Worker) answers from.
//
//   node scripts/i18nDefaultNames.mjs                write the data file
//   node scripts/i18nDefaultNames.mjs --check        exit 1 when it is stale
//   --locales <dir>  --out <file>                    read / write elsewhere
//
// Runs after `lingui compile` in npm run i18n:build, and scripts/i18nCheck.mjs
// calls check(). Parser: @lingui/format-po's own parsePoFile (a declared
// dependency; it wraps pofile-ts).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { parsePoFile } from '@lingui/format-po';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const LOCALES_DIR = join(ROOT, 'src/locales');
export const OUT_FILE = join(ROOT, 'src/lib/defaultNames.data.js');
export const CONTEXT = 'default name';

// English names the app no longer writes but old data still holds, so they have
// no catalog entry. 'Untitled list' was the name of a cluster in list view.
export const LEGACY = ['Untitled list'];

// { 'Untitled doc': ['Untitled doc', 'Documento sin título', …], … }, both
// levels sorted, so the file is the same every time.
export function collect(localesDir = LOCALES_DIR) {
  const table = new Map();
  const add = (english, name) => {
    if (!table.has(english)) table.set(english, new Set([english]));
    if (name && name.trim()) table.get(english).add(name);
  };
  for (const dir of readdirSync(localesDir, { withFileTypes: true })) {
    const file = join(localesDir, dir.name, 'messages.po');
    if (!dir.isDirectory() || !existsSync(file)) continue;
    for (const item of parsePoFile(readFileSync(file, 'utf8')).items) {
      if (item.msgctxt !== CONTEXT || item.obsolete) continue;
      add(item.msgid, item.msgstr?.[0]);
    }
  }
  for (const english of LEGACY) add(english);
  const out = {};
  for (const english of [...table.keys()].sort()) out[english] = [...table.get(english)].sort();
  return out;
}

// The names already in the data file. Append-only: a name once written into
// people's data stays recognised even if a later translation edit drops it
// from the catalogs. Not part of collect(), which the tests run on fixtures.
export function readExisting(out = OUT_FILE) {
  if (!existsSync(out)) return {};
  const text = readFileSync(out, 'utf8');
  try { return JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1)); } catch (_) { return {}; }
}

// The collected table plus every name in `existing`, both levels sorted as collect() sorts them.
export function union(table, existing) {
  const out = {};
  for (const english of [...new Set([...Object.keys(table), ...Object.keys(existing)])].sort()) {
    out[english] = [...new Set([...(table[english] || []), ...(existing[english] || [])])].sort();
  }
  return out;
}

export function render(table) {
  return `// Generated by scripts/i18nDefaultNames.mjs from the catalogs' "default name"
// entries (npm run i18n:build). Do not edit. Plain data: the Worker imports it.
export default ${JSON.stringify(table, null, 2)};
`;
}

export function check({ localesDir = LOCALES_DIR, out = OUT_FILE } = {}) {
  const want = render(union(collect(localesDir), readExisting(out)));
  return existsSync(out) && readFileSync(out, 'utf8') === want;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const flag = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
  const localesDir = flag('--locales', LOCALES_DIR);
  const out = flag('--out', OUT_FILE);
  if (args.includes('--check')) {
    if (!check({ localesDir, out })) {
      console.error('src/lib/defaultNames.data.js is behind the catalogs: run npm run i18n:build and commit.');
      process.exit(1);
    }
    console.log('Default names are in sync with the catalogs.');
  } else {
    writeFileSync(out, render(union(collect(localesDir), readExisting(out))));
    console.log(`Wrote ${out}`);
  }
}
