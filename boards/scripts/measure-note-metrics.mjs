// measure-note-metrics.mjs — measures per-character advance widths (em) for the
// note-height estimator and writes src/lib/noteFitMetrics.js.
//
//   NOTE_FONT_DIR=/path/to/aileron-woff2 node scripts/measure-note-metrics.mjs
//
// NOTE_FONT_DIR holds aileron-400.woff2, aileron-600.woff2, aileron-700.woff2
// (fontsource). For each character and weight we keep the MAX of Aileron and the
// system fallback stack, so the estimate holds whichever font actually renders.
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.env.NOTE_FONT_DIR;
if (!dir) { console.error('Set NOTE_FONT_DIR to the folder with aileron-{400,600,700}.woff2'); process.exit(1); }

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'lib', 'noteFitMetrics.js');

const chars = [];
for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCodePoint(c));
for (let c = 0xc0; c <= 0xff; c++) chars.push(String.fromCodePoint(c));
for (const ch of '–—•·’‘“”…→←★☆☐☑✓✔€£¥©®™°') chars.push(ch);

const face = (w) => {
  const b64 = fs.readFileSync(path.join(dir, `aileron-${w}.woff2`)).toString('base64');
  return `@font-face{font-family:aileronm;font-weight:${w};src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
};

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<!doctype html><style>${face(400)}${face(600)}${face(700)}
span{white-space:pre;font-size:100px;position:absolute;left:0;top:0}</style><body></body>`);
await page.evaluate(() => Promise.all([
  document.fonts.load('400 100px aileronm'), document.fonts.load('700 100px aileronm'),
]));
await page.evaluate(() => document.fonts.ready);

const FAMILIES = { aileron: 'aileronm', fallback: '-apple-system, system-ui, sans-serif' };
const measure = (family, weight) => page.evaluate(({ chars, family, weight }) => {
  const s = document.createElement('span');
  s.style.fontFamily = family; s.style.fontWeight = String(weight);
  document.body.appendChild(s);
  const out = {};
  for (const ch of chars) { s.textContent = ch; out[ch] = s.getBoundingClientRect().width / 100; }
  s.remove();
  return out;
}, { chars, family, weight });

const tables = {};
for (const [name, fam] of Object.entries(FAMILIES)) {
  for (const [wname, w] of [['regular', 400], ['bold', 700]]) tables[`${name}-${wname}`] = await measure(fam, w);
}
await browser.close();

const r4 = (n) => Math.round(n * 1e4) / 1e4;
const merged = { regular: {}, bold: {} };
for (const wname of ['regular', 'bold']) {
  for (const ch of chars) merged[wname][ch] = r4(Math.max(tables[`aileron-${wname}`][ch], tables[`fallback-${wname}`][ch]));
}
const maxOf = (t) => Math.max(...Object.values(t));
const fmt = (t) => '{' + Object.entries(t).map(([k, v]) => `${JSON.stringify(k)}:${v}`).join(',') + '}';

const src = `// GENERATED by \`NOTE_FONT_DIR=… node scripts/measure-note-metrics.mjs\` — do not edit by hand.
//
// Per-character advance widths in em (measured at 100px) for the note-height
// estimator (noteFit.js). Each value is the MAX of Aileron and the system
// fallback stack (-apple-system, system-ui, sans-serif) at that weight.
// unknown* = the widest measured character; wide = CJK / emoji (>= U+1100, not in the table).
export const NOTE_EM = {
  regular: ${fmt(merged.regular)},
  bold: ${fmt(merged.bold)},
  unknownRegular: ${r4(maxOf(merged.regular))},
  unknownBold: ${r4(maxOf(merged.bold))},
  wide: 1.0,
};
`;
fs.writeFileSync(OUT, src);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${chars.length} chars)`);
